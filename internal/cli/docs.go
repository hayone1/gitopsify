package cli

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// newGenDocs writes the command reference (docs/commands.md). Hidden: it is
// for maintainers, run by `make docs`.
func newGenDocs(o *options) *cobra.Command {
	return &cobra.Command{
		Use:    "gen-docs <file>",
		Short:  "Write the command reference as Markdown",
		Hidden: true,
		Args:   cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return os.WriteFile(args[0], []byte(commandReference(cmd.Root())), 0o644)
		},
	}
}

// commandReference renders every visible command with its flags, grouped
// the way --help groups them.
func commandReference(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString("# Command reference\n\n")
	b.WriteString("<!-- Generated by `make docs` from the command definitions; edit internal/cli instead. -->\n\n")
	b.WriteString("Every command reads `./gitopsify.yaml` when it exists (or `--config`); flags override it. ")
	b.WriteString("Run `gitopsify <command> --help` for the same information in the terminal.\n\n")
	var cmds []*cobra.Command
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, sub := range c.Commands() {
			if !sub.IsAvailableCommand() || sub.Name() == "help" || sub.Name() == "completion" {
				continue
			}
			cmds = append(cmds, sub)
			walk(sub)
		}
	}
	walk(root)
	b.WriteString("| Command | |\n|---|---|\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", c.CommandPath(), anchor(c.CommandPath()), c.Short)
	}
	b.WriteString("| `gitopsify completion bash\\|zsh\\|fish\\|powershell` | Shell completion scripts |\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n", c.CommandPath(), c.Short+".")
		if c.Long != "" {
			b.WriteString("```text\n" + strings.TrimSpace(c.Long) + "\n```\n\n")
		}
		if c.Runnable() {
			fmt.Fprintf(&b, "Usage: `%s`\n\n", c.UseLine())
		}
		if c.Example != "" {
			b.WriteString("```sh\n" + strings.TrimRight(c.Example, "\n") + "\n```\n\n")
		}
		sections := map[string][]*pflag.Flag{}
		c.LocalFlags().VisitAll(func(f *pflag.Flag) {
			if f.Hidden || f.Name == "help" {
				return
			}
			g := "Flags"
			if a := f.Annotations[groupAnnotation]; len(a) > 0 {
				g = a[0]
				if g == groupSource {
					return // global; listed once at the end
				}
			}
			sections[g] = append(sections[g], f)
		})
		for _, g := range append([]string{"Flags"}, groupOrder...) {
			if fs := sections[g]; len(fs) > 0 {
				fmt.Fprintf(&b, "**%s**\n\n%s\n", g, flagTable(fs))
			}
		}
	}
	b.WriteString("\n## Global flags\n\nEvery command accepts these.\n\n")
	var global, source []*pflag.Flag
	root.PersistentFlags().VisitAll(func(f *pflag.Flag) {
		if a := f.Annotations[groupAnnotation]; len(a) > 0 && a[0] == groupSource {
			source = append(source, f)
		} else {
			global = append(global, f)
		}
	})
	b.WriteString(flagTable(global))
	b.WriteString("\n**Source cluster access** (see [authentication](authentication.md))\n\n")
	b.WriteString(flagTable(source))
	return b.String()
}

func flagTable(fs []*pflag.Flag) string {
	sort.SliceStable(fs, func(i, j int) bool { return fs[i].Name < fs[j].Name })
	var b strings.Builder
	b.WriteString("| Flag | Default | |\n|---|---|---|\n")
	for _, f := range fs {
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		def := f.DefValue
		switch def {
		case "", "[]", "false", "0s":
			def = ""
		default:
			def = "`" + def + "`"
		}
		usage := strings.ReplaceAll(f.Usage, "|", `\|`)
		fmt.Fprintf(&b, "| %s | %s | %s |\n", name, def, usage)
	}
	return b.String()
}

func anchor(s string) string {
	return strings.ReplaceAll(strings.ToLower(s), " ", "-")
}
