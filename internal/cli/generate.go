type gitFlags struct {
	commit  bool
	push    bool
	message string
	// pushBranch pushes to this branch instead of the revision, for a
	// pull request (generate only: migrate bootstraps from the revision).
	pushBranch string
}

func (g *gitFlags) add(cmd *cobra.Command) {
	cmd.Flags().BoolVar(&g.commit, "commit", false, "git init (if needed) and commit the output")
	cmd.Flags().BoolVar(&g.push, "push", false, "commit and push the output to --repo-url (with your git credentials, or $GITOPSIFY_PUSH_TOKEN over HTTPS)")
	cmd.Flags().StringVar(&g.message, "message", "Generated by gitopsify", "commit message")
	inGroup(cmd.Flags(), groupGit, "commit", "push", "message")
}

func newGenerate(o *options) *cobra.Command {
	var dryRun, exitCode bool
	var g gitFlags
	cmd := &cobra.Command{
		Use:   "generate",
		Short: "Write the GitOps repository",
		Long: `Runs the whole pipeline against the source cluster and writes the repository.

Maturity levels:
  --tool none     clean Kustomize apps and Helm values; wire them up yourself
  --tool argocd   plus Applications/ApplicationSets, an AppProject and a pinned
                  Argo CD bootstrap (--pattern app-of-apps|applicationset|single)
  --tool flux     plus Flux Kustomizations, HelmReleases and a pinned Flux bootstrap

Re-running it updates the files it generated and keeps files you added. Files
changed by hand since gitopsify wrote them are overwritten with a warning
(--edited keep|fail), files it didn't write where it writes stop the run
(--unmanaged overwrite|keep), and --keep paths are never touched (all three are
spec.output.merge in gitopsify.yaml).

For scheduled runs (a CronJob or CI job that opens a pull request):
--push-branch pushes to a branch of its own, only when the output changed, and
--exit-code exits with status 2 when files changed. Sealed and SOPS-encrypted
Secrets keep their ciphertext while the Secret doesn't change, so an unchanged
cluster gives an unchanged repository.`,
		Example: `  # test was built by hand; generate an Argo CD app-of-apps repo for uat
  gitopsify generate --context test --tool argocd --env uat=uat-cluster \
    --repo-url https://github.com/acme/platform-gitops.git

  # Flux, one repository per environment, sealed Secrets
  gitopsify generate --tool flux --layout repo-per-env --env uat --env prod \
    --secrets sealed-secrets --repo-url git@github.com:acme/gitops.git

  # just one app and what it needs, as plain manifests
  gitopsify generate -r deployment/shop/web -o ./web

  # Argo CD takes over the cluster it was exported from
  gitopsify generate --tool argocd --adopt --env prod=prod --repo-url ...

  # nightly: regenerate and push to a pull request branch when anything changed
  gitopsify generate -c gitops/gitopsify.yaml -o gitops --push --push-branch gitopsify/drift`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			cfg, err := o.load(cmd)
			if err != nil {
				return err
			}
			u := o.ui()
			if g.pushBranch != "" && !g.push {
				return errors.New("--push-branch needs --push")
			}
			if g.pushBranch != "" && cfg.Output.Repo.Path != "" {
				return errors.New("--push-branch: with --repo-path (output.repo.path) the output is a directory of a repository you commit yourself")
			}
			res, err := scanAndFinish(cmd.Context(), o, u, cfg)
			if err != nil {
				return err
			}
			if dryRun {
				wr, err := planOutput(cfg, res, o.force)
				if err != nil {
					return err
				}
				printPlan(u, cfg, wr)
				if g.push && !u.Quiet {
					u.Step("compared with %s as it is; --push would first check the remote branch out into an empty directory", cfg.Output.Dir)
				}
				return changedExit(exitCode, wr)
			}
			if g.commit || g.push {
				if err := checkoutRemote(u, cfg); err != nil {
					return err
				}
			}
			wr, err := writeOutput(u, cfg, res, o.force)
			if err != nil {
				return err
			}
			if g.commit || g.push {
				if err := publish(u, cfg, g); err != nil {
					return err
				}
			}
			if g.pushBranch == "" || g.pushBranch == cfg.Output.Repo.Revision {
				nextSteps(u, cfg, g.push)
			}
			return changedExit(exitCode, wr)
		},
	}
	o.addScope(cmd.Flags())
	o.addSecrets(cmd.Flags())
	o.addOutput(cmd.Flags())
	o.addTarget(cmd.Flags())
	g.add(cmd)
	cmd.Flags().StringVar(&g.pushBranch, "push-branch", "", "with --push: push to this branch instead of --revision, for a pull request; nothing is pushed when the output didn't change")
	inGroup(cmd.Flags(), groupGit, "push-branch")
	cmd.Flags().BoolVar(&dryRun, "dry-run", false, "show what would be written, changed and removed, without writing")
	cmd.Flags().BoolVar(&exitCode, "exit-code", false, "exit with status 2 when the output changed (or, with --dry-run, would change)")
	cmd.Flags().BoolVarP(&o.interactive, "interactive", "i", false, "choose the apps to migrate interactively")
	return cmd
}

// changedExit is --exit-code's status: 2 when files changed.
func changedExit(exitCode bool, wrs []*render.WriteResult) error {
	if !exitCode {
		return nil
	}
	for _, wr := range wrs {
		if len(wr.Changed) > 0 {
			return &exitError{code: 2}
		}
	}
	return nil
}

// scanAndFinish runs the pipeline, letting the user pick apps in between
// when --interactive is set.
func scanAndFinish(ctx context.Context, o *options, u *ui.UI, cfg *config.Config) (*pipeline.Result, error) {
	popts, err := o.pipelineOptions(cfg, u.Step)
	if err != nil {
		return nil, err
	}
	res, err := pipeline.Scan(ctx, popts)
	if err != nil {
		return nil, err
	}
	if o.interactive {
		if !u.Interactive {
			return nil, fmt.Errorf("--interactive needs a terminal")
		}
		if err := selectApps(u, cfg, res); err != nil {
			return nil, err
		}
	}
	if err := pipeline.Finish(ctx, popts, res); err != nil {
		return nil, err
	}
	return res, nil
}

func selectApps(u *ui.UI, cfg *config.Config, res *pipeline.Result) error {
	var options []ui.Option
	var selected []string
	for _, a := range res.Inventory.Apps {
		label := fmt.Sprintf("%-28s wave %3d  %3d objects", a.Name, a.Wave, len(a.Objects))
		if a.Release != nil {
			label += fmt.Sprintf("  helm %s %s", a.Release.Chart.Name, a.Release.Chart.Version)
		}
		options = append(options, ui.Option{Label: label, Value: a.Name})
		selected = append(selected, a.Name)
	}
	if err := u.MultiSelect("Apps to migrate", "space toggles, / filters, enter confirms", options, &selected); err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, s := range selected {
		keep[s] = true
	}
	var drop []string
	for _, a := range res.Inventory.Apps {
		if !keep[a.Name] {
			drop = append(drop, a.Name)
		}
	}
	sort.Strings(drop)
	cfg.Scope.ExcludeApps = append(cfg.Scope.ExcludeApps, drop...)
	pipeline.ExcludeApps(res.Inventory, drop)
	return nil
}

func writeOptions(cfg *config.Config, force, dryRun bool) render.WriteOptions {
	o := render.WriteOptions{Force: force, DryRun: dryRun}
	if m := cfg.Output.Merge; m != nil {
		o.Edited, o.Unmanaged, o.Keep = m.Edited, m.Unmanaged, m.Keep
	}
	return o
}

// planOutput works out what writing would do.
func planOutput(cfg *config.Config, res *pipeline.Result, force bool) ([]*render.WriteResult, error) {
	if gone := droppedEnvs(cfg); len(gone) > 0 && !force {
		return nil, droppedEnvsError(cfg, gone)
	}
	wr, err := res.Tree.Write(cfg.Output.Dir, writeOptions(cfg, force, true))
	if err != nil {
		return nil, err
	}
	return []*render.WriteResult{wr}, nil
}

func droppedEnvsError(cfg *config.Config, gone []string) error {
	return fmt.Errorf("%s has environment(s) %s that this run doesn't generate: writing would remove their files (and a push would delete them from the repository). "+
		"List every environment (--env for each, or none to use gitopsify.yaml's); to update one, run generate for all of them and then bootstrap --env <name>. "+
		"Pass --force to remove them", cfg.Output.Dir, strings.Join(gone, ", "))
}

// printPlan shows what --dry-run would do.
func printPlan(u *ui.UI, cfg *config.Config, wrs []*render.WriteResult) {
	for _, wr := range wrs {
		changed, created := map[string]bool{}, map[string]bool{}
		for _, p := range append(append([]string(nil), wr.Changed...), wr.Outside...) {
			changed[p] = true
		}
		for _, p := range wr.Created {
			created[p] = true
		}
		var news, edits int
		for _, p := range wr.Written {
			mark := "  "
			switch {
			case created[p]:
				mark, news = "+ ", news+1
			case changed[p]:
				mark, edits = "~ ", edits+1
			}
			u.Println(mark + filepath.Join(cfg.Output.Dir, p))
		}
		for _, p := range wr.Removed {
			u.Println("- " + filepath.Join(cfg.Output.Dir, p))
		}
		for _, p := range wr.Kept {
			u.Println("= " + filepath.Join(cfg.Output.Dir, p) + u.Dim("  (kept as it is)"))
		}
		if !u.Quiet {
			u.Step("%d new, %d changed, %d removed, %d kept (+ new, ~ changed, - removed, = kept)", news, edits, len(wr.Removed), len(wr.Kept))
		}
		mergeWarnings(u, wr, true)
	}
}

// mergeWarnings tells about the files people changed or added.
func mergeWarnings(u *ui.UI, wr *render.WriteResult, dryRun bool) {
	verb := "overwrote"
	if dryRun {
		verb = "would overwrite"
	}
	kept := map[string]bool{}
	for _, p := range wr.Kept {
		kept[p] = true
	}
	var overwritten []string
	for _, p := range wr.Edited {
		if !kept[p] {
			overwritten = append(overwritten, p)
		}
	}
	if len(overwritten) > 0 {
		u.Warn("%s %d files changed by hand since gitopsify wrote them (%s); keep such changes in files of your own, or set output.merge.edited: keep",
			verb, len(overwritten), someOf(overwritten))
	}
	if len(wr.Overwritten) > 0 {
		u.Warn("%s %d files gitopsify didn't write: %s", verb, len(wr.Overwritten), someOf(wr.Overwritten))
	}
	if len(wr.Kept) > 0 && !dryRun {
		u.Step("kept %d files as they are (hand edits, files of yours, output.merge.keep): %s", len(wr.Kept), someOf(wr.Kept))
	}
	if len(wr.Reused) > 0 {
		u.Step("%d encrypted Secrets unchanged: their ciphertext stays", len(wr.Reused))
	}
}

func someOf(list []string) string {
	if len(list) <= 4 {
		return strings.Join(list, ", ")
	}
	return strings.Join(list[:4], ", ") + fmt.Sprintf(" and %d more", len(list)-4)
}

func writeOutput(u *ui.UI, cfg *config.Config, res *pipeline.Result, force bool) ([]*render.WriteResult, error) {
	if gone := droppedEnvs(cfg); len(gone) > 0 && !force {
		return nil, droppedEnvsError(cfg, gone)
	}
	wr, err := res.Tree.Write(cfg.Output.Dir, writeOptions(cfg, force, false))
	if err != nil {
		return nil, err
	}
	inv := res.Inventory
	u.Success("wrote %d files for %d apps to %s (%d changed)", len(wr.Written), len(inv.Apps), cfg.Output.Dir, len(wr.Changed))
	if len(wr.Removed) > 0 {
		u.Step("removed %d files the previous run generated and this one doesn't", len(wr.Removed))
	}
	mergeWarnings(u, wr, false)
	if n := len(allWarnings(inv)); n > 0 {
		u.Warn("%d warnings; see %s", n, filepath.Join(cfg.Output.Dir, "MIGRATION_REPORT.md"))
	}
	if n := len(inv.SecretActions); n > 0 {
		u.Warn("%d Secrets need action in the target; see MIGRATION_REPORT.md", n)
	}
	return []*render.WriteResult{wr}, nil
}

// droppedEnvs lists the environments of the output directory's previous
// run (its gitopsify.yaml) that this run doesn't generate.
func droppedEnvs(cfg *config.Config) []string {
	prev, err := config.Load(filepath.Join(cfg.Output.Dir, "gitopsify.yaml"))
	if err != nil {
		return nil // none yet, or not gitopsify's
	}
	now := map[string]bool{}
	for _, e := range cfg.Environments {
		now[e.Name] = true
	}
	var gone []string
	for _, e := range prev.Environments {
		if !now[e.Name] {
			gone = append(gone, e.Name)
		}
	}
	return gone
}

// layoutDirs returns the repository directories of the output: one, or one
// per environment with repo-per-env, with their remotes.
func layoutDirs(cfg *config.Config) map[string]string {
	if cfg.Output.Layout == config.LayoutRepoPerEnv {
		out := map[string]string{}
		for _, e := range cfg.Environments {
			url := e.RepoURL
			if url == "" {
				url = cfg.Output.Repo.URL
			}
			out[filepath.Join(cfg.Output.Dir, e.Name)] = url
		}
		return out
	}
	return map[string]string{cfg.Output.Dir: cfg.Output.Repo.URL}
}

// envDir returns the generated repository root of an environment.
func envDir(cfg *config.Config, env string) string {
	if cfg.Output.Layout == config.LayoutRepoPerEnv {
		return filepath.Join(cfg.Output.Dir, env)
	}
	return cfg.Output.Dir
}

// checkoutRemote checks out the remote branch into output directories that
// aren't repositories yet, so pushes continue the remote's history.
func checkoutRemote(u *ui.UI, cfg *config.Config) error {
	if cfg.Output.Repo.Path != "" {
		return nil
	}
	for dir, remote := range layoutDirs(cfg) {
		done, err := gitrepo.CheckoutEnv(context.Background(), dir, remote, cfg.Output.Repo.Revision, gitAuthEnv(remote))
		if err != nil {
			return fmt.Errorf("checking out %s into %s: %w", remote, dir, err)
		}
		if done {
			u.Step("checked out %s (%s) into %s", remote, cfg.Output.Repo.Revision, dir)
		}
	}
	return nil
}

// gitAuthEnv gives git a token for an HTTPS remote from
// $GITOPSIFY_PUSH_TOKEN (and $GITOPSIFY_PUSH_USERNAME, default
// x-access-token), for CI jobs and CronJobs without a credential helper.
// (bootstrap's $GITOPSIFY_GIT_TOKEN is the GitOps tool's, often read-only.)
// It goes in git's environment, never in a URL or a file, and only to the
// host of the configured repository.
func gitAuthEnv(remote string) []string {
	token := os.Getenv("GITOPSIFY_PUSH_TOKEN")
	u, err := url.Parse(remote)
	if token == "" || err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil {
		return nil
	}
	user := envOr("GITOPSIFY_PUSH_USERNAME", "x-access-token")
	basic := base64.StdEncoding.EncodeToString([]byte(user + ":" + token))
	return []string{"GIT_CONFIG_COUNT=1", "GIT_CONFIG_KEY_0=http.https://" + u.Host + "/.extraHeader", "GIT_CONFIG_VALUE_0=Authorization: Basic " + basic}
}

func publish(u *ui.UI, cfg *config.Config, g gitFlags) error {
	dirs := layoutDirs(cfg)
	keys := make([]string, 0, len(dirs))
	for d := range dirs {
		keys = append(keys, d)
	}
	sort.Strings(keys)
	for _, dir := range keys {
		remote := dirs[dir]
		if cfg.Output.Repo.Path != "" {
			u.Warn("output.repo.path is set: commit %s into the repository yourself", dir)
			continue
		}
		res, err := gitrepo.Publish(gitrepo.Options{Dir: dir, Remote: remote, Branch: cfg.Output.Repo.Revision, PushTo: g.pushBranch,
			Message: g.message, Push: g.push, Env: gitAuthEnv(remote)})
		if err != nil {
			return err
		}
		switch {
		case res.Unchanged:
			u.Step("%s: %s (%s) already holds this output; nothing pushed", dir, remote, cfg.Output.Repo.Revision)
		case res.UpToDate:
			u.Step("%s: %s (%s) already holds this output; nothing pushed", dir, remote, g.pushBranch)
		case res.Pushed && g.pushBranch != "" && g.pushBranch != cfg.Output.Repo.Revision:
			u.Success("pushed %s (%s) to %s branch %s, for a pull request into %s", dir, res.Commit, remote, g.pushBranch, cfg.Output.Repo.Revision)
			if res.Replaced != "" {
				u.Step("replaced gitopsify's earlier commit %.12s on %s", res.Replaced, g.pushBranch)
			}
		case res.Pushed:
			u.Success("pushed %s (%s) to %s", dir, res.Commit, remote)
		case res.Committed:
			u.Success("committed %s (%s)", dir, res.Commit)
		default:
			u.Step("%s: nothing to commit", dir)
		}
	}
	return nil
}

func nextSteps(u *ui.UI, cfg *config.Config, pushed bool) {
	if u.Quiet {
		return
	}
	env := cfg.Environments[0].Name
	u.Heading("Next steps")
	var steps []string
	steps = append(steps, "Review "+filepath.Join(envDir(cfg, env), "MIGRATION_REPORT.md"))
	switch cfg.Output.Tool {
	case config.ToolNone:
		steps = append(steps, "Apply in order: "+filepath.Join(envDir(cfg, env), "apply-"+env+".sh")+" --context <target>")
	default:
		if !pushed {
			steps = append(steps, fmt.Sprintf("Push %s to %s (or rerun with --push)", cfg.Output.Dir, cfg.Output.Repo.URL))
		}
		steps = append(steps,
			fmt.Sprintf("gitopsify check --env %s && gitopsify diff --env %s", env, env),
			fmt.Sprintf("gitopsify bootstrap --env %s", env))
	}
	for i, s := range steps {
		u.Printf("  %d. %s\n", i+1, s)
	}
}

func newRules(o *options) *cobra.Command {
	return &cobra.Command{
		Use:   "rules",
		Short: "List the built-in exclusion rules",
		Long:  "Lists the rules that leave system and controller-generated objects out. Disable one with --disable-rule or scope.disableDefaultRules.",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			u := o.ui()
			var rows [][]string
			for _, r := range filterRules() {
				rows = append(rows, []string{r[0], r[1]})
			}
			u.Table([]string{"Rule", "Excludes"}, rows)
			return nil
		},
	}
}
