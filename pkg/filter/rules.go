func alreadyManaged(o *model.Object, _ *model.Inventory) (bool, string) {
	a, l := o.Live.GetAnnotations(), o.Live.GetLabels()
	if id := a["argocd.argoproj.io/tracking-id"]; id != "" {
		app, _, _ := strings.Cut(id, ":")
		return true, "managed by Argo CD application " + app
	}
	if l["argocd.argoproj.io/instance"] != "" {
		return true, "managed by Argo CD application " + l["argocd.argoproj.io/instance"]
	}
	for _, p := range []string{"kustomize.toolkit.fluxcd.io", "helm.toolkit.fluxcd.io"} {
		if n := l[p+"/name"]; n != "" {
			return true, fmt.Sprintf("managed by Flux %s %s/%s", strings.Split(p, ".")[0], l[p+"/namespace"], n)
		}
	}
	if tool, ok := gitopsGroups[o.Ref.Group]; ok {
		if o.Ref.Group == "argoproj.io" && o.Ref.Kind != "Application" && o.Ref.Kind != "ApplicationSet" && o.Ref.Kind != "AppProject" {
			return false, ""
		}
		return true, tool + " configuration object"
	}
	return false, ""
}
