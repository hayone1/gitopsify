func controllerEndpoints(o *model.Object, inv *model.Inventory) (bool, string) {
	switch o.Ref.GroupKind() {
	case "EndpointSlice.discovery.k8s.io":
		l := o.Live.GetLabels()
		switch l["endpointslice.kubernetes.io/managed-by"] {
		case "endpointslice-controller.k8s.io", "endpointslicemirroring-controller.k8s.io":
			return true, "maintained by the EndpointSlice controller"
		}
		name := l["kubernetes.io/service-name"]
		if o.Ref.Namespace == "default" && name == "kubernetes" {
			return true, "maintained by the API server"
		}
		if svc := inv.Get(model.Ref{Kind: "Service", Namespace: o.Ref.Namespace, Name: name}); svc != nil {
			if sel, _, _ := unstructured.NestedMap(svc.Live.Object, "spec", "selector"); len(sel) > 0 {
				return true, "maintained for Service " + name
			}
		}
		return false, ""
	case "Endpoints":
		svc := inv.Get(model.Ref{Kind: "Service", Namespace: o.Ref.Namespace, Name: o.Ref.Name})
		if svc == nil {
			return false, ""
		}
		if sel, _, _ := unstructured.NestedMap(svc.Live.Object, "spec", "selector"); len(sel) > 0 {
			return true, "maintained for Service " + o.Ref.Name
		}
		if t, _, _ := unstructured.NestedString(svc.Live.Object, "spec", "type"); t == "ExternalName" {
			return true, "ExternalName Service"
		}
	}
	return false, ""
}

// systemComponentRBAC excludes the cluster-wide RBAC of components that run in
// system namespaces (CNI, CSI, cloud controllers, kind's local-path
// provisioner): ClusterRoleBindings whose every subject is a system service
// account or system: user/group, and ClusterRoles only such bindings use.
func systemComponentRBAC() Rule {
	var index map[string][]*model.Object
	var indexed *model.Inventory
	systemSubjects := func(b *model.Object) bool {
		subjects, _, _ := unstructured.NestedSlice(b.Live.Object, "subjects")
		if len(subjects) == 0 {
			return false
		}
		for _, s := range subjects {
			m, _ := s.(map[string]any)
			name, _ := m["name"].(string)
			ns, _ := m["namespace"].(string)
			switch m["kind"] {
			case "ServiceAccount":
				if !match.Glob(SystemNamespaces, ns) {
					return false
				}
			default:
				if !strings.HasPrefix(name, "system:") {
					return false
				}
			}
		}
		return true
	}
	return Rule{
		Name:        "system-component-rbac",
		Description: "ClusterRoleBindings that only grant system-namespace service accounts or system: users, and ClusterRoles used only by them (CNI, CSI and cloud components)",
		Match: func(o *model.Object, inv *model.Inventory) (bool, string) {
			switch o.Ref.GroupKind() {
			case "ClusterRoleBinding.rbac.authorization.k8s.io":
				if systemSubjects(o) {
					return true, "binds only system components"
				}
			case "ClusterRole.rbac.authorization.k8s.io":
				if indexed != inv {
					index, indexed = map[string][]*model.Object{}, inv
					for _, b := range inv.Objects {
						if b.Ref.Group != "rbac.authorization.k8s.io" || (b.Ref.Kind != "ClusterRoleBinding" && b.Ref.Kind != "RoleBinding") {
							continue
						}
						if k, _, _ := unstructured.NestedString(b.Live.Object, "roleRef", "kind"); k == "ClusterRole" {
							n, _, _ := unstructured.NestedString(b.Live.Object, "roleRef", "name")
							index[n] = append(index[n], b)
						}
					}
				}
				bindings := index[o.Ref.Name]
				if len(bindings) == 0 {
					return false, ""
				}
				for _, b := range bindings {
					if b.Ref.Kind == "RoleBinding" && !match.Glob(SystemNamespaces, b.Ref.Namespace) || b.Ref.Kind == "ClusterRoleBinding" && !systemSubjects(b) {
						return false, ""
					}
				}
				return true, "used only by system components"
			}
			return false, ""
		},
	}
}

func defaultServiceAccount(o *model.Object, _ *model.Inventory) (bool, string) {
	if o.Ref.Group != "" || o.Ref.Kind != "ServiceAccount" || o.Ref.Name != "default" {
		return false, ""
	}
	if !uncustomizedServiceAccount(o) {
		return false, ""
	}
	return true, "not customized"
}

// uncustomizedServiceAccount reports whether a ServiceAccount holds nothing a
// person set: no pull secrets but generated ones, no token automount setting,
// no annotations but bookkeeping.
func uncustomizedServiceAccount(o *model.Object) bool {
	ips, _, _ := unstructured.NestedSlice(o.Live.Object, "imagePullSecrets")
	for _, s := range ips {
		m, _ := s.(map[string]any)
		name, _ := m["name"].(string)
		if !model.GeneratedPullSecret(o.Ref.Name, name) {
			return false
		}
	}
	if _, found, _ := unstructured.NestedBool(o.Live.Object, "automountServiceAccountToken"); found {
		return false
	}
	for k := range o.Live.GetAnnotations() {
		switch k {
		case "kubectl.kubernetes.io/last-applied-configuration", "openshift.io/internal-registry-pull-secret-ref":
		default:
			return false
		}
	}
	return true
}

// platformServiceAccount matches the ServiceAccounts OpenShift creates in
// every namespace and the pull secrets it generates for ServiceAccounts.
func platformServiceAccount(o *model.Object, _ *model.Inventory) (bool, string) {
	switch {
	case o.Ref.Group == "" && o.Ref.Kind == "ServiceAccount":
		switch o.Ref.Name {
		case "builder", "deployer", "pipeline":
		default:
			return false, ""
		}
		_, openshift := o.Live.GetAnnotations()["openshift.io/internal-registry-pull-secret-ref"]
		ips, _, _ := unstructured.NestedSlice(o.Live.Object, "imagePullSecrets")
		for _, s := range ips {
			m, _ := s.(map[string]any)
			if name, _ := m["name"].(string); model.GeneratedPullSecret(o.Ref.Name, name) {
				openshift = true
			}
		}
		if openshift && uncustomizedServiceAccount(o) {
			return true, "created by OpenShift in every namespace"
		}
	case o.IsSecret():
		a := o.Live.GetAnnotations()
		sa := a["kubernetes.io/service-account.name"]
		if a["openshift.io/internal-registry-auth-token.service-account"] != "" || sa != "" && model.GeneratedPullSecret(sa, o.Ref.Name) {
			return true, "registry pull secret generated by OpenShift"
		}
	}
	return false, ""
}

