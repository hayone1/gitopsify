// Labels and annotations gitopsify writes.
const (
	LabelWave       = "gitopsify.io/wave"
	LabelEnv        = "gitopsify.io/env"
	LabelApp        = "gitopsify.io/app"
	annArgoSyncWave = "argocd.argoproj.io/sync-wave"
	annArgoSyncOpts = "argocd.argoproj.io/sync-options"
	annArgoCompare  = "argocd.argoproj.io/compare-options"
	annFluxPrune    = "kustomize.toolkit.fluxcd.io/prune"
	kustomizeAPI    = "kustomize.config.k8s.io/v1beta1"
)

// Options configure Render.
type Options struct {
	Config  *config.Config
	Secrets *secrets.Result
	// Version of gitopsify, recorded in generated files.
	Version string
}

type renderer struct {
	cfg  *config.Config
	inv  *model.Inventory
	opts Options
	tree *Tree
	// migratedNS holds the namespaces whose Namespace object is migrated.
	migratedNS map[string]bool
}

// layout is one GitOps tree: the whole output (folder-per-env) or one
// environment's repository (repo-per-env).
type layout struct {
	// root is the tree's directory inside the output.
	root     string
	envs     []config.Environment
	repoURL  string
	overlays bool
}

func (l layout) file(p ...string) string { return path.Join(append([]string{l.root}, p...)...) }

func (l layout) appBase(app string) string {
	if l.overlays {
		return path.Join("apps", app, "base")
	}
	return path.Join("apps", app)
}

func (l layout) appEnv(app, env string) string {
	if l.overlays {
		return path.Join("apps", app, "envs", env)
	}
	return path.Join("apps", app)
}

func (l layout) chartHome(app string) string { return path.Join("apps", app, "charts") }

// envDir is the directory holding an environment's GitOps tool objects.
func (l layout) envDir(tool, env string) string { return path.Join(tool, env) }

// Render renders the inventory.
func Render(inv *model.Inventory, opts Options) (*Tree, error) {
	r := &renderer{cfg: opts.Config, inv: inv, opts: opts, tree: NewTree(), migratedNS: map[string]bool{}}
	for _, o := range inv.Objects {
		if !o.Excluded && o.IsNamespace() {
			r.migratedNS[o.Ref.Name] = true
		}
	}
	for _, l := range r.layouts() {
		if err := r.renderLayout(l); err != nil {
			return nil, err
		}
	}
	if err := r.rootFiles(); err != nil {
		return nil, err
	}
	return r.tree, nil
}

func (r *renderer) layouts() []layout {
	if r.cfg.Output.Layout == config.LayoutRepoPerEnv {
		var out []layout
		for _, e := range r.cfg.Environments {
			url := e.RepoURL
			if url == "" {
				url = r.cfg.Output.Repo.URL
			}
			out = append(out, layout{root: e.Name, envs: []config.Environment{e}, repoURL: url})
		}
		return out
	}
	return []layout{{envs: r.cfg.Environments, repoURL: r.cfg.Output.Repo.URL, overlays: true}}
}

// repoPath is the path, inside the Git repository, of a path relative to a
// layout's root.
func (r *renderer) repoPath(p string) string {
	return path.Join(r.cfg.Output.Repo.Path, p)
}

func (r *renderer) renderLayout(l layout) error {
	for _, a := range r.inv.Apps {
		if err := r.renderApp(l, a); err != nil {
			return fmt.Errorf("app %s: %w", a.Name, err)
		}
	}
	var err error
	switch r.cfg.Output.Tool {
	case config.ToolArgoCD:
		err = r.renderArgoCD(l)
	case config.ToolFlux:
		err = r.renderFlux(l)
	default:
		err = r.renderPlain(l)
	}
	if err != nil {
		return err
	}
	if r.usesSOPS() {
		b, err := secrets.SOPSConfig(r.cfg.Secrets.SOPS)
		if err != nil {
			return err
		}
		r.tree.Add(l.file(".sops.yaml"), b)
	}
	r.tree.Add(l.file("README.md"), r.readme(l))
	r.tree.Add(l.file("MIGRATION_REPORT.md"), r.report(l))
	r.tree.Add(l.file(".gitignore"), []byte("# Plain-text Secrets for the local and external-secrets strategies.\n"+secrets.LocalDir+"/\n"))
	return nil
}

// rootFiles writes the effective configuration and local secret files at the
// output root.
func (r *renderer) rootFiles() error {
	b, err := r.cfg.Marshal()
	if err != nil {
		return err
	}
	header := "# Generated by gitopsify " + r.opts.Version + ". Re-run `gitopsify generate -c gitopsify.yaml` to regenerate.\n"
	r.tree.Add("gitopsify.yaml", append([]byte(header), b...))
	if r.opts.Secrets != nil {
		for p, data := range r.opts.Secrets.LocalFiles {
			r.tree.Add(p, data)
		}
	}
	if r.cfg.Output.Layout == config.LayoutRepoPerEnv {
		r.tree.Add(".gitignore", []byte(secrets.LocalDir+"/\n"))
	}
	return nil
}

func (r *renderer) usesSOPS() bool {
	for _, o := range r.inv.Objects {
		if o.Encrypt && !o.Excluded {
			return true
		}
	}
	return false
}

// appObject is an object of an app with the file it is written to.
type appObject struct {
	o    *model.Object
	out  *unstructured.Unstructured
	file string
}

// appObjects returns the objects an app writes, decorated with the
// annotations the GitOps tool needs, with unique file names.
func (r *renderer) appObjects(a *model.App) []*appObject {
	used := map[string]int{}
	var out []*appObject
	for _, o := range a.Objects {
		if o.Out == nil && len(o.EnvOut) == 0 {
			continue
		}
		var u *unstructured.Unstructured
		if o.Out != nil {
			u = r.decorate(o.Out.DeepCopy(), a)
		}
		name := fileName(o, a)
		used[name]++
		if n := used[name]; n > 1 {
			name = strings.TrimSuffix(name, ".yaml") + fmt.Sprintf("-%d.yaml", n)
		}
		out = append(out, &appObject{o: o, out: u, file: name})
	}
	return out
}

func fileName(o *model.Object, a *model.App) string {
	kind := o.Ref.Kind
	if o.Out != nil {
		kind = o.Out.GetKind()
	} else {
		for _, e := range o.EnvOut {
			kind = e.GetKind()
			break
		}
	}
	base := strings.ToLower(kind) + "-" + o.Ref.Name
	if o.Namespaced && a.Namespace == "" {
		base = o.Ref.Namespace + "-" + base
	}
	base = sanitizeFile(base)
	// Names can be 253 characters long, file names only 255 bytes.
	if len(base) > 180 {
		sum := sha256.Sum256([]byte(base))
		base = base[:170] + "-" + hex.EncodeToString(sum[:])[:8]
	}
	return base + ".yaml"
}

func sanitizeFile(s string) string {
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-', r == '.', r == '_':
			return r
		case r >= 'A' && r <= 'Z':
			return r + 32
		}
		return '-'
	}, s)
}

// decorate adds GitOps tool annotations to an object.
func (r *renderer) decorate(u *unstructured.Unstructured, a *model.App) *unstructured.Unstructured {
	protect := match.AnyKind(r.cfg.Adopt.ProtectKinds, match.KindInfo{Group: u.GroupVersionKind().Group, Kind: u.GetKind()})
	ann := u.GetAnnotations()
	if ann == nil {
		ann = map[string]string{}
	}
	switch r.cfg.Output.Tool {
	case config.ToolArgoCD:
		if protect {
			ann[annArgoSyncOpts] = joinOpt(ann[annArgoSyncOpts], "Prune=false", "Delete=false")
		}
		if r.cfg.Output.ArgoCD.Pattern == config.PatternSingle && config.True(r.cfg.Ordering.Enabled, true) {
			ann[annArgoSyncWave] = fmt.Sprint(a.Wave)
		}
	case config.ToolFlux:
		if protect {
			ann[annFluxPrune] = "disabled"
		}
	}
	if len(ann) > 0 {
		u.SetAnnotations(ann)
	}
	return u
}

func joinOpt(existing string, opts ...string) string {
	have := map[string]bool{}
	var parts []string
	for _, p := range strings.Split(existing, ",") {
		if p = strings.TrimSpace(p); p != "" && !have[p] {
			have[p] = true
			parts = append(parts, p)
		}
	}
	for _, p := range opts {
		if !have[p] {
			parts = append(parts, p)
		}
	}
	return strings.Join(parts, ",")
}

// WaveLabel encodes a wave as a label value; label values must start with a
// letter or digit, so -5 becomes "w-5".
func WaveLabel(wave int) string { return fmt.Sprintf("w%d", wave) }

// appsByWave returns the apps sorted by wave, then name.
func (r *renderer) appsByWave() []*model.App {
	apps := append([]*model.App(nil), r.inv.Apps...)
	sort.SliceStable(apps, func(i, j int) bool {
		if apps[i].Wave != apps[j].Wave {
			return apps[i].Wave < apps[j].Wave
		}
		return apps[i].Name < apps[j].Name
	})
	return apps
}

// needsCreateNamespace reports whether an app deploys into a namespace whose
// Namespace object is not migrated (for example a release in kube-system,
// which exists everywhere, or a namespace that was excluded).
func (r *renderer) needsCreateNamespace(a *model.App) bool {
	return a.Namespace != "" && !r.migratedNS[a.Namespace] && a.Namespace != "default" && !match.Glob([]string{"kube-*"}, a.Namespace)
}

func kustomization(resources []string, extra map[string]any) map[string]any {
	k := map[string]any{"apiVersion": kustomizeAPI, "kind": "Kustomization"}
	if len(resources) > 0 {
		k["resources"] = toAnySlice(resources)
	}
	for key, v := range extra {
		k[key] = v
	}
	return k
}

func toAnySlice(s []string) []any {
	out := make([]any, len(s))
	for i, v := range s {
		out[i] = v
	}
	return out
}

// relPath returns the path of target relative to dir (both slash paths
// relative to the same root).
func relPath(dir, target string) string {
	d := strings.Split(path.Clean(dir), "/")
	t := strings.Split(path.Clean(target), "/")
	i := 0
	for i < len(d) && i < len(t) && d[i] == t[i] {
		i++
	}
	var parts []string
	for range d[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, t[i:]...)
	if len(parts) == 0 {
		return "."
	}
	return path.Join(parts...)
}
