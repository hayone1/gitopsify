const argoAPI = "argoproj.io/v1alpha1"

// applicationHealthLua restores the health assessment of Application objects
// that Argo CD dropped in 1.8; without it app-of-apps sync waves don't wait
// for child applications.
const applicationHealthLua = `hs = {}
hs.status = "Progressing"
hs.message = ""
if obj.status ~= nil then
  if obj.status.health ~= nil then
    hs.status = obj.status.health.status
    if obj.status.health.message ~= nil then
      hs.message = obj.status.health.message
    end
  end
end
return hs
`

// ArgoCDInstallURL returns the upstream install manifest of a version.
func ArgoCDInstallURL(version string) string {
	return "https://raw.githubusercontent.com/argoproj/argo-cd/" + version + "/manifests/install.yaml"
}

func (r *renderer) renderArgoCD(l layout) error {
	// Applications of every environment usually share one Argo CD:
	// prod + eu-web and prod-eu + web would both be prod-eu-web.
	seen := map[string]string{}
	for _, env := range r.cfg.Environments {
		for _, a := range r.inv.Apps {
			name := r.argoName(l, a.Name, env.Name)
			who := fmt.Sprintf("app %s of environment %s", a.Name, env.Name)
			if other, ok := seen[name]; ok {
				return fmt.Errorf("the Argo CD Application %s would be both %s and %s; rename an environment", name, other, who)
			}
			seen[name] = who
		}
	}
	if err := r.argoBootstrap(l); err != nil {
		return err
	}
	for _, env := range l.envs {
		if err := r.argoEnv(l, env); err != nil {
			return fmt.Errorf("environment %s: %w", env.Name, err)
		}
	}
	return nil
}

// argoBootstrap writes argocd/bootstrap: the pinned upstream install plus the
// configuration the generated apps rely on.
func (r *renderer) argoBootstrap(l layout) error {
	a := r.cfg.Output.ArgoCD
	dir := "argocd/bootstrap"
	ns := map[string]any{"apiVersion": "v1", "kind": "Namespace", "metadata": map[string]any{"name": a.Namespace}}
	if err := r.tree.AddYAML(l.file(dir, "namespace.yaml"), ns); err != nil {
		return err
	}
	cm := map[string]any{
		"apiVersion": "v1", "kind": "ConfigMap",
		"metadata": map[string]any{"name": "argocd-cm", "namespace": a.Namespace},
		"data": map[string]any{
			"application.resourceTrackingMethod":                     "annotation",
			"resource.customizations.health.argoproj.io_Application": applicationHealthLua,
		},
	}
	if r.hasKustomizeHelm() {
		cm["data"].(map[string]any)["kustomize.buildOptions"] = "--enable-helm"
	}
	if err := r.tree.AddYAML(l.file(dir, "argocd-cm.yaml"), cm); err != nil {
		return err
	}
	patches := []any{map[string]any{"path": "argocd-cm.yaml"}}
	if a.Pattern == config.PatternApplicationSet && config.True(r.cfg.Ordering.Enabled, true) {
		params := map[string]any{
			"apiVersion": "v1", "kind": "ConfigMap",
			"metadata": map[string]any{"name": "argocd-cmd-params-cm", "namespace": a.Namespace},
			"data":     map[string]any{"applicationsetcontroller.enable.progressive.syncs": "true"},
		}
		if err := r.tree.AddYAML(l.file(dir, "argocd-cmd-params-cm.yaml"), params); err != nil {
			return err
		}
		patches = append(patches, map[string]any{"path": "argocd-cmd-params-cm.yaml"})
	}
	k := kustomization([]string{"namespace.yaml", ArgoCDInstallURL(a.Version)}, map[string]any{
		"namespace": a.Namespace,
		"patches":   patches,
	})
	return r.tree.AddYAML(l.file(dir, "kustomization.yaml"), k)
}

func (r *renderer) hasKustomizeHelm() bool {
	if r.cfg.Output.ArgoCD.Pattern != config.PatternSingle {
		return false
	}
	for _, a := range r.inv.Apps {
		if a.IsHelm() {
			return true
		}
	}
	return false
}

// argoName is the Application name of an app. It always carries the
// environment: one Argo CD instance often manages several environments, and
// names generated by separate runs must not collide.
func (r *renderer) argoName(l layout, app, env string) string {
	return group.Name(env + "-" + app)
}

// projectName is the AppProject of an environment: the default project name
// gets the environment appended; a project chosen by the user is used as is
// unless the tree holds several environments.
func (r *renderer) projectName(l layout, env string) string {
	p := r.cfg.Output.ArgoCD.Project
	if p == "default" {
		return p
	}
	if p == config.DefaultArgoProject || len(l.envs) > 1 {
		return group.Name(p + "-" + env)
	}
	return p
}

func destination(env config.Environment, namespace string) map[string]any {
	d := map[string]any{}
	if env.Cluster.Name != "" {
		d["name"] = env.Cluster.Name
	} else {
		d["server"] = env.Cluster.Server
	}
	if namespace != "" {
		d["namespace"] = namespace
	}
	return d
}

func (r *renderer) argoEnv(l layout, env config.Environment) error {
	a := r.cfg.Output.ArgoCD
	envDir := l.envDir("argocd", env.Name)
	appsDir := path.Join(envDir, "apps")
	project := r.projectName(l, env.Name)

	// Never Argo CD's own default project: other applications use it.
	if config.True(a.CreateProject, true) && project != "default" {
		if err := r.tree.AddYAML(l.file(appsDir, "project.yaml"), r.appProject(l, env, project)); err != nil {
			return err
		}
	}
	for _, s := range r.ociRepoSecrets() {
		name, _ := s["metadata"].(map[string]any)["name"].(string)
		if err := r.tree.AddYAML(l.file(appsDir, "repository-"+name+".yaml"), s); err != nil {
			return err
		}
	}
	switch a.Pattern {
	case config.PatternAppOfApps:
		for _, app := range r.inv.Apps {
			if err := r.tree.AddYAML(l.file(appsDir, app.Name+".yaml"), r.application(l, env, app, project)); err != nil {
				return err
			}
		}
	case config.PatternApplicationSet:
		if err := r.applicationSet(l, env, envDir, appsDir, project); err != nil {
			return err
		}
	case config.PatternSingle:
		allDir := path.Join(envDir, "all")
		var resources []string
		for _, app := range r.appsByWave() {
			resources = append(resources, relPath(allDir, l.appEnv(app.Name, env.Name)))
		}
		if err := r.tree.AddYAML(l.file(allDir, "kustomization.yaml"), kustomization(resources, nil)); err != nil {
			return err
		}
		app := &model.App{Name: "all"}
		spec := r.appSpec(l, env, app, project)
		spec["source"] = map[string]any{"repoURL": l.repoURL, "targetRevision": r.cfg.Output.Repo.Revision, "path": r.repoPath(allDir)}
		obj := map[string]any{
			"apiVersion": argoAPI, "kind": "Application",
			"metadata": map[string]any{"name": r.argoName(l, "all", env.Name), "namespace": a.Namespace, "labels": map[string]any{LabelEnv: env.Name}},
			"spec":     spec,
		}
		if err := r.tree.AddYAML(l.file(appsDir, "all.yaml"), obj); err != nil {
			return err
		}
	}
	root := map[string]any{
		"apiVersion": argoAPI, "kind": "Application",
		"metadata": map[string]any{
			"name":      group.Name("gitopsify-" + env.Name),
			"namespace": a.Namespace,
			"labels":    map[string]any{LabelEnv: env.Name},
		},
		"spec": map[string]any{
			"project": "default",
			"source": map[string]any{
				"repoURL":        l.repoURL,
				"targetRevision": r.cfg.Output.Repo.Revision,
				"path":           r.repoPath(appsDir),
			},
			"destination": map[string]any{"server": "https://kubernetes.default.svc", "namespace": a.Namespace},
			// Pruning here only removes Application objects. They have no
			// resources finalizer, so the workloads stay.
			"syncPolicy": map[string]any{"automated": map[string]any{"prune": true, "selfHeal": true}},
		},
	}
	return r.tree.AddYAML(l.file(envDir, "root.yaml"), root)
}

func (r *renderer) appProject(l layout, env config.Environment, name string) map[string]any {
	repos := map[string]bool{l.repoURL: true}
	for _, a := range r.inv.Apps {
		if a.IsHelm() && a.Release.Mode == model.HelmModeChart {
			repos[argoRepoURL(a.Release.Repo.URL)] = true
		}
	}
	var sourceRepos []string
	for u := range repos {
		sourceRepos = append(sourceRepos, u)
	}
	sort.Strings(sourceRepos)
	return map[string]any{
		"apiVersion": argoAPI, "kind": "AppProject",
		"metadata": map[string]any{
			"name": name, "namespace": r.cfg.Output.ArgoCD.Namespace,
			"annotations": map[string]any{annArgoSyncWave: "-100"},
		},
		"spec": map[string]any{
			"description":              "Migrated by gitopsify",
			"sourceRepos":              toAnySlice(sourceRepos),
			"destinations":             []any{destination(env, "*")},
			"clusterResourceWhitelist": []any{map[string]any{"group": "*", "kind": "*"}},
		},
	}
}

// argoRepoURL converts oci://registry/path into the form Argo CD expects for
// OCI Helm repositories (no scheme, enableOCI on the repository Secret).
func argoRepoURL(u string) string { return strings.TrimPrefix(u, "oci://") }

// ociRepoSecrets declares the OCI Helm repositories charts come from; Argo CD
// needs them registered with enableOCI.
func (r *renderer) ociRepoSecrets() []map[string]any {
	seen := map[string]bool{}
	var out []map[string]any
	for _, a := range r.inv.Apps {
		if !a.IsHelm() || a.Release.Mode != model.HelmModeChart || !a.Release.Repo.IsOCI() {
			continue
		}
		url := argoRepoURL(a.Release.Repo.URL)
		if seen[url] {
			continue
		}
		seen[url] = true
		name := group.Name(url)
		out = append(out, map[string]any{
			"apiVersion": "v1", "kind": "Secret",
			"metadata": map[string]any{
				"name": name, "namespace": r.cfg.Output.ArgoCD.Namespace,
				"labels":      map[string]any{"argocd.argoproj.io/secret-type": "repository"},
				"annotations": map[string]any{annArgoSyncWave: "-100"},
			},
			"stringData": map[string]any{"type": "helm", "name": name, "url": url, "enableOCI": "true"},
		})
	}
	return out
}

func (r *renderer) syncPolicy(app *model.App, automated bool) map[string]any {
	a := r.cfg.Output.ArgoCD
	opts := []string{}
	if config.True(a.ServerSideApply, true) {
		opts = append(opts, "ServerSideApply=true")
	}
	if r.cfg.Adopt.Enabled {
		// Leave fields owned by kubectl and other managers in place on the
		// first sync instead of taking them over and deleting them.
		opts = append(opts, "ClientSideApplyMigration=false")
	}
	if app.SkipDryRun {
		opts = append(opts, "SkipDryRunOnMissingResource=true")
	}
	if r.needsCreateNamespace(app) {
		opts = append(opts, "CreateNamespace=true")
	}
	p := map[string]any{
		"retry": map[string]any{
			"limit":   int64(5),
			"backoff": map[string]any{"duration": "10s", "factor": int64(2), "maxDuration": "3m"},
		},
	}
	if len(opts) > 0 {
		p["syncOptions"] = toAnySlice(opts)
	}
	if automated && config.True(a.AutoSync, true) {
		p["automated"] = map[string]any{"prune": config.True(a.Prune, true), "selfHeal": config.True(a.SelfHeal, true)}
	}
	return p
}

func (r *renderer) appSpec(l layout, env config.Environment, app *model.App, project string) map[string]any {
	return map[string]any{
		"project":     project,
		"destination": destination(env, app.Namespace),
		"syncPolicy":  r.syncPolicy(app, true),
	}
}

// application renders the Application of one app.
func (r *renderer) application(l layout, env config.Environment, app *model.App, project string) map[string]any {
	spec := r.appSpec(l, env, app, project)
	if app.IsHelm() {
		spec["sources"] = r.helmSources(l, env, app)
	} else {
		spec["source"] = map[string]any{
			"repoURL":        l.repoURL,
			"targetRevision": r.cfg.Output.Repo.Revision,
			"path":           r.repoPath(l.appEnv(app.Name, env.Name)),
		}
	}
	meta := map[string]any{
		"name":      r.argoName(l, app.Name, env.Name),
		"namespace": r.cfg.Output.ArgoCD.Namespace,
		"labels":    map[string]any{LabelEnv: env.Name, LabelApp: app.Name, LabelWave: WaveLabel(app.Wave)},
	}
	if config.True(r.cfg.Ordering.Enabled, true) {
		meta["annotations"] = map[string]any{annArgoSyncWave: fmt.Sprint(app.Wave)}
	}
	return map[string]any{"apiVersion": argoAPI, "kind": "Application", "metadata": meta, "spec": spec}
}

func (r *renderer) valueFiles(l layout, env config.Environment, app *model.App) []any {
	if !l.overlays {
		return []any{"$values/" + r.repoPath(path.Join(l.appBase(app.Name), "values.yaml"))}
	}
	return []any{
		"$values/" + r.repoPath(path.Join(l.appBase(app.Name), "values.yaml")),
		"$values/" + r.repoPath(path.Join(l.appEnv(app.Name, env.Name), "values.yaml")),
	}
}

// helmSources returns the sources of a multi-source Helm Application: the
// chart, and the Git repository the values files come from.
func (r *renderer) helmSources(l layout, env config.Environment, app *model.App) []any {
	c := r.chartRef(l, app)
	helmCfg := map[string]any{
		"releaseName":             app.Release.Name,
		"valueFiles":              r.valueFiles(l, env, app),
		"ignoreMissingValueFiles": true,
	}
	var chart map[string]any
	if c.vendored {
		chart = map[string]any{"repoURL": l.repoURL, "targetRevision": r.cfg.Output.Repo.Revision, "path": r.repoPath(c.chartPath), "helm": helmCfg}
	} else {
		chart = map[string]any{"repoURL": argoRepoURL(c.repoURL), "chart": c.chart, "targetRevision": c.version, "helm": helmCfg}
	}
	values := map[string]any{"repoURL": l.repoURL, "targetRevision": r.cfg.Output.Repo.Revision, "ref": "values"}
	return []any{chart, values}
}

// applicationSet writes one ApplicationSet per environment, driven by a Git
// files generator over one JSON file per app.
func (r *renderer) applicationSet(l layout, env config.Environment, envDir, appsDir, project string) error {
	cfgDir := path.Join(envDir, "config")
	waves := map[int]bool{}
	for _, app := range r.inv.Apps {
		// "path" is reserved by the Git files generator in Go templates.
		params := map[string]string{
			"appName":         r.argoName(l, app.Name, env.Name),
			"app":             app.Name,
			"namespace":       app.Namespace,
			"wave":            WaveLabel(app.Wave),
			"skipDryRun":      fmt.Sprint(app.SkipDryRun),
			"createNamespace": fmt.Sprint(r.needsCreateNamespace(app)),
		}
		waves[app.Wave] = true
		if app.IsHelm() {
			c := r.chartRef(l, app)
			vf := r.valueFiles(l, env, app)
			params["releaseName"] = app.Release.Name
			params["valuesBase"] = strings.TrimPrefix(vf[0].(string), "$values/")
			params["valuesEnv"] = strings.TrimPrefix(vf[len(vf)-1].(string), "$values/")
			if c.vendored {
				params["type"] = "helm-git"
				params["appPath"] = r.repoPath(c.chartPath)
			} else {
				params["type"] = "helm"
				params["repoURL"] = argoRepoURL(c.repoURL)
				params["chart"] = c.chart
				params["version"] = c.version
			}
		} else {
			params["type"] = "kustomize"
			params["appPath"] = r.repoPath(l.appEnv(app.Name, env.Name))
		}
		b, err := json.MarshalIndent(params, "", "  ")
		if err != nil {
			return err
		}
		r.tree.Add(l.file(cfgDir, app.Name+".json"), append(b, '\n'))
	}

	a := r.cfg.Output.ArgoCD
	ordered := config.True(r.cfg.Ordering.Enabled, true) && len(waves) > 1
	repo, rev := l.repoURL, r.cfg.Output.Repo.Revision
	// Indented for spec.syncPolicy in the patch below.
	syncOpts := "      - ServerSideApply=true\n"
	if !config.True(a.ServerSideApply, true) {
		syncOpts = ""
	}
	if r.cfg.Adopt.Enabled {
		syncOpts += "      - ClientSideApplyMigration=false\n"
	}
	automated := ""
	if config.True(a.AutoSync, true) && !ordered {
		// RollingSync drives syncs itself and turns automated sync off.
		automated = fmt.Sprintf("    automated:\n      prune: %t\n      selfHeal: %t\n", config.True(a.Prune, true), config.True(a.SelfHeal, true))
	}
	patch := `spec:
{{- if eq .type "helm" }}
  sources:
    - repoURL: '{{ .repoURL }}'
      chart: '{{ .chart }}'
      targetRevision: '{{ .version }}'
      helm:
        releaseName: '{{ .releaseName }}'
        ignoreMissingValueFiles: true
        valueFiles:
          - '$values/{{ .valuesBase }}'
          - '$values/{{ .valuesEnv }}'
    - repoURL: ` + repo + `
      targetRevision: ` + rev + `
      ref: values
{{- else if eq .type "helm-git" }}
  sources:
    - repoURL: ` + repo + `
      targetRevision: ` + rev + `
      path: '{{ .appPath }}'
      helm:
        releaseName: '{{ .releaseName }}'
        ignoreMissingValueFiles: true
        valueFiles:
          - '$values/{{ .valuesBase }}'
          - '$values/{{ .valuesEnv }}'
    - repoURL: ` + repo + `
      targetRevision: ` + rev + `
      ref: values
{{- else }}
  source:
    repoURL: ` + repo + `
    targetRevision: ` + rev + `
    path: '{{ .appPath }}'
{{- end }}
  syncPolicy:
` + automated + `    syncOptions:
` + syncOpts + `{{- if eq .skipDryRun "true" }}
      - SkipDryRunOnMissingResource=true
{{- end }}
{{- if eq .createNamespace "true" }}
      - CreateNamespace=true
{{- end }}
`
	dest := destination(env, "{{ .namespace }}")
	spec := map[string]any{
		"goTemplate":        true,
		"goTemplateOptions": []any{"missingkey=default"},
		"generators": []any{map[string]any{"git": map[string]any{
			"repoURL":  repo,
			"revision": rev,
			"files":    []any{map[string]any{"path": r.repoPath(path.Join(cfgDir, "*.json"))}},
		}}},
		"template": map[string]any{
			"metadata": map[string]any{
				"name":   "{{ .appName }}",
				"labels": map[string]any{LabelEnv: env.Name, LabelApp: "{{ .app }}", LabelWave: "{{ .wave }}"},
			},
			"spec": map[string]any{
				"project":     project,
				"destination": dest,
			},
		},
		"templatePatch": patch,
		// An Application that drops out of the generator (its config file
		// removed, a bad push) leaves its objects running: they were
		// running before gitopsify, and Argo CD would otherwise delete them.
		"syncPolicy": map[string]any{"preserveResourcesOnDeletion": true},
	}
	if ordered {
		var ws []int
		for w := range waves {
			ws = append(ws, w)
		}
		sort.Ints(ws)
		var steps []any
		for _, w := range ws {
			steps = append(steps, map[string]any{"matchExpressions": []any{map[string]any{
				"key": LabelWave, "operator": "In", "values": []any{WaveLabel(w)},
			}}})
		}
		spec["strategy"] = map[string]any{"type": "RollingSync", "rollingSync": map[string]any{"steps": steps}}
	}
	obj := map[string]any{
		"apiVersion": argoAPI, "kind": "ApplicationSet",
		"metadata": map[string]any{"name": group.Name("gitopsify-" + env.Name), "namespace": a.Namespace},
		"spec":     spec,
	}
	return r.tree.AddYAML(l.file(appsDir, "applicationset.yaml"), obj)
}
