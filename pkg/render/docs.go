func envNames(l layout) []string {
	var out []string
	for _, e := range l.envs {
		out = append(out, e.Name)
	}
	return out
}

func (r *renderer) readme(l layout) []byte {
	var b strings.Builder
	cfg := r.cfg
	src := r.inv.Source
	fmt.Fprintf(&b, "# GitOps repository: %s\n\n", strings.Join(envNames(l), ", "))
	fmt.Fprintf(&b, "Generated by [gitopsify](https://github.com/hayone1/gitopsify) %s from %s.\n", r.opts.Version, src)
	b.WriteString("Regenerate with `gitopsify generate -c gitopsify.yaml`; files you add by hand are kept.\n\n")
	b.WriteString("Read [MIGRATION_REPORT.md](MIGRATION_REPORT.md) before the first sync: it lists what was left out and why, and what needs your attention.\n\n")

	b.WriteString("## Layout\n\n```\n")
	switch {
	case l.overlays:
		b.WriteString("apps/<app>/base/              manifests (or Helm values) exported from the source cluster\n")
		b.WriteString("apps/<app>/envs/<env>/        per-environment overlay: patches and values overrides\n")
	default:
		b.WriteString("apps/<app>/                   manifests (or Helm values) for this environment\n")
	}
	b.WriteString("apps/<app>/charts/<chart>/    charts rebuilt from Helm releases whose repository is unknown\n")
	switch cfg.Output.Tool {
	case config.ToolArgoCD:
		b.WriteString("argocd/bootstrap/             Argo CD install, pinned, with the settings the apps rely on\n")
		b.WriteString("argocd/<env>/root.yaml        the one object to apply by hand; it manages argocd/<env>/apps\n")
		switch cfg.Output.ArgoCD.Pattern {
		case config.PatternAppOfApps:
			b.WriteString("argocd/<env>/apps/            one Application per app, ordered by sync waves\n")
		case config.PatternApplicationSet:
			b.WriteString("argocd/<env>/apps/            the ApplicationSet of the environment\n")
			b.WriteString("argocd/<env>/config/          one JSON file per app, read by the ApplicationSet's Git generator\n")
		case config.PatternSingle:
			b.WriteString("argocd/<env>/all/             a Kustomization of every app; ordered by resource sync waves\n")
		}
	case config.ToolFlux:
		b.WriteString("clusters/<env>/flux-system/   Flux install (pinned) and the root GitRepository/Kustomization\n")
		b.WriteString("clusters/<env>/apps/          one Flux Kustomization per app, ordered with dependsOn\n")
	default:
		b.WriteString("apply-<env>.sh                applies every app in order with server-side apply\n")
	}
	b.WriteString("```\n\n")

	b.WriteString("## Apps\n\n| Wave | App | Type | Namespace | Objects | Depends on |\n|---:|---|---|---|---:|---|\n")
	for _, a := range r.appsByWave() {
		typ := "manifests"
		if a.Release != nil {
			typ = fmt.Sprintf("Helm `%s` %s (%s)", a.Release.Chart.Name, a.Release.Chart.Version, a.Release.Mode)
		}
		ns := a.Namespace
		if ns == "" {
			ns = "—"
		}
		deps := strings.Join(a.DependsOn, ", ")
		if deps == "" {
			deps = "—"
		}
		fmt.Fprintf(&b, "| %d | %s | %s | %s | %d | %s |\n", a.Wave, a.Name, typ, ns, len(a.Objects), deps)
	}
	b.WriteString("\n## Bootstrap\n\n")
	r.bootstrapDocs(&b, l)

	b.WriteString("\n## Before the first sync\n\n")
	b.WriteString("1. Read MIGRATION_REPORT.md, especially *Secrets that need action* and *Warnings*.\n")
	b.WriteString("2. Check the target cluster: `gitopsify check -c gitopsify.yaml --env <env>` verifies API versions, StorageClasses and IngressClasses.\n")
	b.WriteString("3. Preview the first sync: `gitopsify diff -c gitopsify.yaml --env <env>` server-side dry-runs every object against the target.\n")
	if cfg.Adopt.Enabled {
		b.WriteString("4. Takeover mode is on: pruning is off and PVCs, Namespaces and CRDs are protected from deletion. Turn pruning on once the first syncs are clean.\n")
	}
	return []byte(b.String())
}

func (r *renderer) bootstrapDocs(b *strings.Builder, l layout) {
	cfg := r.cfg
	env := l.envs[0].Name
	switch cfg.Output.Tool {
	case config.ToolArgoCD:
		fmt.Fprintf(b, "Push this directory to `%s` (branch `%s`), then either run\n\n", l.repoURL, cfg.Output.Repo.Revision)
		fmt.Fprintf(b, "```sh\ngitopsify bootstrap -c gitopsify.yaml --env %s\n```\n\nor do the same by hand:\n\n", env)
		fmt.Fprintf(b, "```sh\nkubectl apply --server-side -k %s\n", "./argocd/bootstrap")
		fmt.Fprintf(b, "kubectl -n %s rollout status deploy/argocd-repo-server deploy/argocd-server\n", cfg.Output.ArgoCD.Namespace)
		b.WriteString("# private repositories: argocd repo add <url> --username ... --password ...\n")
		fmt.Fprintf(b, "kubectl apply -f %s\n```\n", "./"+path.Join("argocd", env, "root.yaml"))
		if cfg.Output.ArgoCD.Pattern == config.PatternApplicationSet && config.True(cfg.Ordering.Enabled, true) {
			b.WriteString("\nThe ApplicationSet orders apps with the progressive-sync `RollingSync` strategy, which Argo CD ships disabled; the bootstrap Kustomization enables it in `argocd-cmd-params-cm`.\n")
		}
	case config.ToolFlux:
		fmt.Fprintf(b, "Push this directory to `%s` (branch `%s`), then either run\n\n", l.repoURL, cfg.Output.Repo.Revision)
		fmt.Fprintf(b, "```sh\ngitopsify bootstrap -c gitopsify.yaml --env %s\n```\n\nor use the Flux CLI, which reuses the same layout:\n\n", env)
		fmt.Fprintf(b, "```sh\nflux bootstrap git --url=%s --branch=%s --path=%s\n```\n", FluxURL(l.repoURL), cfg.Output.Repo.Revision, r.repoPath(path.Join("clusters", env)))
		if r.usesSOPS() {
			fmt.Fprintf(b, "\nSecrets are SOPS-encrypted. Create the decryption key in the cluster before the first sync:\n\n```sh\nkubectl -n %s create secret generic %s --from-file=age.agekey=<your age key file>\n```\n", cfg.Output.Flux.Namespace, cfg.Secrets.SOPS.DecryptionSecret)
		}
	default:
		b.WriteString("These are plain manifests: wire them into the tool of your choice. Every `apps/<app>/envs/<env>` directory is a Kustomization (`kustomize build`, with `--enable-helm` for Helm apps).\n\n")
		fmt.Fprintf(b, "To apply an environment by hand, in order:\n\n```sh\n./apply-%s.sh --context <target-context>\n```\n", env)
	}
}

func (r *renderer) report(l layout) []byte {
	inv := r.inv
	var b strings.Builder
	src := inv.Source
	b.WriteString("# Migration report\n\n")
	fmt.Fprintf(&b, "Source: %s. Target environments: %s.\n\n", src, strings.Join(envNames(l), ", "))

	included, excluded := inv.Included(), inv.Excluded()
	migratedReleases, skippedReleases := 0, 0
	for _, rel := range inv.Releases {
		if rel.Skip {
			skippedReleases++
		} else {
			migratedReleases++
		}
	}
	b.WriteString("## Summary\n\n| | Count |\n|---|---:|\n")
	fmt.Fprintf(&b, "| Objects discovered | %d |\n| Objects migrated | %d |\n| Objects excluded | %d |\n", len(inv.Objects), len(included), len(excluded))
	fmt.Fprintf(&b, "| Helm releases migrated | %d |\n| Helm releases skipped | %d |\n| Apps | %d |\n", migratedReleases, skippedReleases, len(inv.Apps))
	fmt.Fprintf(&b, "| Secrets that need action | %d |\n| Warnings | %d |\n\n", len(inv.SecretActions), r.warningCount())

	if len(inv.Releases) > 0 {
		b.WriteString("## Helm releases\n\n| Release | Chart | Version | Mode | Repository | Resolved by | Notes |\n|---|---|---|---|---|---|---|\n")
		for _, rel := range inv.Releases {
			repo, src, mode := "—", "—", string(rel.Mode)
			if rel.Repo != nil {
				// A code span: no HTML inside, only its own delimiters.
				repo, src = "`"+strings.NewReplacer("`", "'", "|", `\|`).Replace(rel.Repo.URL)+"`", escape(rel.Repo.Source)
			}
			notes := strings.Join(rel.Warnings, "; ")
			if rel.Skip {
				mode, notes = "skipped", rel.SkipReason
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", escape(rel.Key()), escape(rel.Chart.Name), escape(rel.Chart.Version), mode, repo, src, escape(notes))
		}
		b.WriteString("\nModes: **chart** pulls the chart from its repository; **vendor** writes the chart, rebuilt from the release, into `apps/<app>/charts/`; **manifests** writes the release's objects as plain manifests (used when the chart can be neither found nor rebuilt).\n\n")
	}

	b.WriteString("## Apps\n\n| Wave | App | Phase | Depends on | Objects |\n|---:|---|---|---|---:|\n")
	for _, a := range r.appsByWave() {
		fmt.Fprintf(&b, "| %d | %s | %s | %s | %d |\n", a.Wave, a.Name, a.Phase, strings.Join(a.DependsOn, ", "), len(a.Objects))
	}

	b.WriteString("\n## Secrets that need action\n\n")
	if len(inv.SecretActions) == 0 {
		b.WriteString("None.\n")
	}
	for _, s := range inv.SecretActions {
		fmt.Fprintf(&b, "- %s\n", mdText(s))
	}

	b.WriteString("\n## Warnings\n\n")
	if r.warningCount() == 0 {
		b.WriteString("None.\n")
	}
	for _, w := range inv.Warnings {
		fmt.Fprintf(&b, "- %s\n", mdText(w))
	}
	for _, rel := range inv.Releases {
		if rel.Skip {
			continue
		}
		for _, w := range rel.Warnings {
			fmt.Fprintf(&b, "- Helm release `%s`: %s\n", rel.Key(), mdText(w))
		}
	}
	for _, o := range included {
		for _, w := range o.Warnings {
			fmt.Fprintf(&b, "- `%s`: %s\n", o.Ref, mdText(w))
		}
	}

	b.WriteString("\n## Excluded objects\n\n")
	if len(excluded) == 0 {
		b.WriteString("None.\n")
	}
	byRule := map[string][]*model.Object{}
	for _, o := range excluded {
		rule, _, _ := strings.Cut(o.Reason, ":")
		byRule[rule] = append(byRule[rule], o)
	}
	rules := make([]string, 0, len(byRule))
	for k := range byRule {
		rules = append(rules, k)
	}
	sort.Strings(rules)
	desc := map[string]string{
		filter.ScopeRule: "Outside the selected scope.",
		filter.HelmRule:  "Part of a Helm release that is not migrated.",
	}
	for _, d := range filter.DefaultRules() {
		desc[d.Name] = d.Description + ". Disable with `scope.disableDefaultRules: [" + d.Name + "]`."
	}
	for _, rule := range rules {
		objs := byRule[rule]
		fmt.Fprintf(&b, "### %s (%d)\n\n", rule, len(objs))
		if d := desc[rule]; d != "" {
			b.WriteString(d + "\n\n")
		}
		if len(objs) > 15 {
			b.WriteString("<details><summary>Objects</summary>\n\n")
		}
		for _, o := range objs {
			_, detail, _ := strings.Cut(o.Reason, ": ")
			fmt.Fprintf(&b, "- `%s` — %s\n", o.Ref, mdText(detail))
		}
		if len(objs) > 15 {
			b.WriteString("\n</details>\n")
		}
		b.WriteString("\n")
	}
	return []byte(b.String())
}

func (r *renderer) warningCount() int {
	n := len(r.inv.Warnings)
	for _, rel := range r.inv.Releases {
		if !rel.Skip {
			n += len(rel.Warnings)
		}
	}
	for _, o := range r.inv.Objects {
		if !o.Excluded {
			n += len(o.Warnings)
		}
	}
	return n
}

// mdText keeps text from clusters and tools (names, messages) from being
// read as HTML by markdown renderers.
var mdText = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace

// escape is mdText for a table cell.
func escape(s string) string { return strings.ReplaceAll(mdText(s), "|", `\|`) }
